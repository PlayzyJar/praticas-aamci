/* USER CODE BEGIN 0 */
void UART_Send(const char *str)
{
  HAL_UART_Transmit(&huart3, (uint8_t *)str, (uint16_t)strlen(str), HAL_MAX_DELAY);
}

static inline uint32_t Dice_From_RNG(uint32_t rng_val)
{
  return (rng_val % 6) + 1;
}

static inline const char* Dice_GetResult(uint32_t machine, uint32_t player)
{
  if (machine > player)
  {
    return "[ Machine ] venceu a rodada!\r\n";
  }
  else if (player > machine)
  {
    return "[ Jogador ] venceu a rodada!\r\n";
  }
  else
  {
    return "Empate!\r\n";
  }
}
